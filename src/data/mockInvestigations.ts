function timeline(startMinsAgo: number, durationMins: number): TimelineEvent[] {
  const labels = [
    'Failure received',
    'Evidence validated',
    'Investigation queued',
    'Gemini analysis started',
    'Classification completed',
    'Similarity search completed',
    'Release risk calculated',
    'Recommendation produced',
  ];
  const step = (durationMins * 60_000) / (labels.length - 1);
  const start = now - startMinsAgo * 60_000;
  return labels.map((label, i) => ({
    id: `t${i}`,
    label,
    at: new Date(start + step * i).toISOString(),
  }));
}

